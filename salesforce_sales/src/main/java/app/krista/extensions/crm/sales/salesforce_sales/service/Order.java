package app.krista.extensions.crm.sales.salesforce_sales.service;

import java.util.Map;

/**
 * Service interface for Order entity.
 * Defines getter methods for all Order fields.
 */
public interface Order {
    
    /**
     * @return Salesforce Order ID
     */
    String getId();
    
    /**
     * @return Order Number (auto-generated by Salesforce)
     */
    String getOrderNumber();
    
    /**
     * @return Account ID associated with this order
     */
    String getAccountId();
    
    /**
     * @return Effective date of the order
     */
    Long getEffectiveDate();
    
    /**
     * @return Order status (Draft, Activated, etc.)
     */
    String getStatus();
    
    /**
     * @return Order description
     */
    String getDescription();
    
    /**
     * @return Customer Authorized By User ID
     */
    String getCustomerAuthorizedById();
    
    /**
     * @return Company Authorized By User ID
     */
    String getCompanyAuthorizedById();
    
    /**
     * @return Order type
     */
    String getType();
    
    /**
     * @return Billing street address
     */
    String getBillingStreet();
    
    /**
     * @return Billing city
     */
    String getBillingCity();
    
    /**
     * @return Billing state
     */
    String getBillingState();
    
    /**
     * @return Billing postal code
     */
    String getBillingPostalCode();
    
    /**
     * @return Billing country
     */
    String getBillingCountry();
    
    /**
     * @return Shipping street address
     */
    String getShippingStreet();
    
    /**
     * @return Shipping city
     */
    String getShippingCity();
    
    /**
     * @return Shipping state
     */
    String getShippingState();
    
    /**
     * @return Shipping postal code
     */
    String getShippingPostalCode();
    
    /**
     * @return Shipping country
     */
    String getShippingCountry();
    
    /**
     * @return Total amount of the order
     */
    Double getTotalAmount();
    
    /**
     * @return Created date timestamp
     */
    Long getCreatedDate();
    
    /**
     * @return Created By User ID
     */
    String getCreatedById();
    
    /**
     * @return Owner User ID
     */
    String getOwnerId();
    
    /**
     * @return Purchase Order Number (custom field)
     * @deprecated Use getCustomFields() instead for dynamic custom field support
     */
    @Deprecated
    String getPoNumber();

    /**
     * @return Extraction Status (custom field)
     * @deprecated Use getCustomFields() instead for dynamic custom field support
     */
    @Deprecated
    String getExtractionStatus();

    /**
     * @return Confidence score (custom field)
     * @deprecated Use getCustomFields() instead for dynamic custom field support
     */
    @Deprecated
    Double getConfidence();

    /**
     * @return Map of dynamic custom fields (fields ending with __c in Salesforce)
     */
    Map<String, Object> getCustomFields();
}

